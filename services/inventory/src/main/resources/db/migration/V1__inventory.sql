CREATE TABLE commands(id VARCHAR(100) PRIMARY KEY, request_hash VARCHAR(64) NOT NULL, response TEXT NOT NULL, created_at VARCHAR(40) NOT NULL);
CREATE TABLE products(
 id VARCHAR(36) PRIMARY KEY,sku VARCHAR(80) NOT NULL UNIQUE,name VARCHAR(180) NOT NULL,category VARCHAR(80) NOT NULL,
 brand VARCHAR(100) NOT NULL,grade VARCHAR(80) NOT NULL,capacity VARCHAR(60) NOT NULL,barcode VARCHAR(100),unit VARCHAR(10) NOT NULL,
 quantity DECIMAL(18,3) NOT NULL DEFAULT 0 CHECK(quantity>=0),selling_price DECIMAL(18,2) NOT NULL CHECK(selling_price>=0),
 reorder_level DECIMAL(18,3) NOT NULL CHECK(reorder_level>=0),image_id VARCHAR(100),created_at VARCHAR(40) NOT NULL
);
CREATE UNIQUE INDEX products_barcode ON products(barcode);
CREATE TABLE job_gates(id VARCHAR(36) PRIMARY KEY,state VARCHAR(20) NOT NULL,revision BIGINT NOT NULL DEFAULT 0);
CREATE TABLE movements(
 id VARCHAR(36) PRIMARY KEY,product_id VARCHAR(36) NOT NULL REFERENCES products(id),kind VARCHAR(20) NOT NULL,
 quantity DECIMAL(18,3) NOT NULL CHECK(quantity>0),unit_price DECIMAL(18,2) NOT NULL,
 job_id VARCHAR(36),issue_id VARCHAR(36),actor VARCHAR(180) NOT NULL,note VARCHAR(500) NOT NULL,created_at VARCHAR(40) NOT NULL
);
CREATE INDEX movements_job ON movements(job_id);
CREATE TABLE outbox(id VARCHAR(36) PRIMARY KEY,type VARCHAR(40) NOT NULL,payload TEXT NOT NULL,delivered BOOLEAN NOT NULL DEFAULT FALSE,attempts INTEGER NOT NULL DEFAULT 0,created_at VARCHAR(40) NOT NULL);
